import { execFile } from 'child_process';
import { promisify } from 'util';
import { mkdir, readFile, readdir, realpath, writeFile } from 'fs/promises';
import path from 'path';
import type { ProjectConfig, TestSuite } from '../shared/types';
import {
  CI_WORKFLOW_PATH,
  collectEnvSecrets,
  generateCiWorkflow,
  isSuziqaiWorkflow,
  type CiIosOptions,
} from '../shared/utils/generateCiWorkflow';

const run = promisify(execFile);

export async function gitRoot(projectPath: string): Promise<string> {
  try {
    const { stdout } = await run('git', ['rev-parse', '--show-toplevel'], { cwd: projectPath });
    return stdout.trim();
  } catch {
    throw new Error(`${projectPath} isn't in a git repository, so there's nowhere to put a GitHub Actions workflow. Run \`git init\` (and push it to GitHub) first.`);
  }
}

/** Writes the workflow unless a hand-written (marker-less) file is already there. */
export async function writeWorkflowFile(repoRoot: string, content: string): Promise<string> {
  const file = path.join(repoRoot, CI_WORKFLOW_PATH);
  const existing = await readFile(file, 'utf-8').catch(() => null);
  if (existing !== null && !isSuziqaiWorkflow(existing)) {
    throw new Error(`${CI_WORKFLOW_PATH} already exists and wasn't generated by suziQai; it won't be overwritten. Rename or delete it to set up CI again.`);
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content, 'utf-8');
  return file;
}

/** The Xcode project's directory (project path or its ios/ folder) and its scheme name. */
export async function detectIosProject(projectPath: string, repoRoot: string): Promise<CiIosOptions> {
  for (const dir of [projectPath, path.join(projectPath, 'ios')]) {
    const files = await readdir(dir).catch(() => [] as string[]);
    const yml = files.includes('project.yml') ? await readFile(path.join(dir, 'project.yml'), 'utf-8') : null;
    const xcodeproj = files.find((f) => f.endsWith('.xcodeproj'));
    if (!yml && !xcodeproj) continue;
    const scheme = yml?.match(/^name:\s*["']?([^"'\n#]+?)["']?\s*$/m)?.[1] ?? xcodeproj?.replace(/\.xcodeproj$/, '');
    return { projectDir: path.relative(repoRoot, dir) || '.', ...(scheme ? { scheme } : {}) };
  }
  return { projectDir: path.relative(repoRoot, projectPath) || '.' };
}

export async function setUpCi(
  projectPath: string,
  config: ProjectConfig,
  suites: TestSuite[],
): Promise<{ path: string; secrets: string[] }> {
  const root = await gitRoot(projectPath);
  // git prints the resolved path; resolve ours too (e.g. /tmp → /private/tmp) so relative paths line up
  const project = await realpath(projectPath);
  const options = config.platform === 'ios'
    ? { ios: await detectIosProject(project, root) }
    : { workingDirectory: path.relative(root, project) || '.' };
  const content = generateCiWorkflow({ config, suites, options });
  const file = await writeWorkflowFile(root, content);
  return { path: file, secrets: collectEnvSecrets(suites) };
}
