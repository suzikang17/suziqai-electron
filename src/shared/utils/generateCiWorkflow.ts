import type { ProjectConfig, Step, TestSuite } from '@shared/types';
import { xcTestClassName } from './generateXCUITest';

/** First line of every workflow suziQai writes; only files that start with it may be regenerated over. */
export const CI_MARKER = '# Generated by suziQai';
export const CI_WORKFLOW_PATH = '.github/workflows/suziqai-tests.yml';

export interface CiIosOptions {
  /** Directory holding the Xcode project (and project.yml, if XcodeGen), relative to the repo root. */
  projectDir?: string;
  scheme?: string;
  /** The UI test target the suites' classes live in. Defaults to `<scheme>UITests`. */
  uiTestTarget?: string;
  /** Simulator name. Falls back to the first available iPhone when the runner image doesn't have it. */
  device?: string;
}

export interface CiWorkflowOptions {
  /** Nightly schedule, UTC. */
  cron?: string;
  branch?: string;
  /** Web: also publish the HTML report to GitHub Pages (main-branch and scheduled runs only). */
  pages?: boolean;
  /** Web: the project's directory relative to the repo root, when it isn't the root. */
  workingDirectory?: string;
  ios?: CiIosOptions;
}

export interface CiWorkflowInput {
  config: ProjectConfig;
  suites: TestSuite[];
  options?: CiWorkflowOptions;
}

export const CI_DEFAULTS = { cron: '0 7 * * *', branch: 'main', device: 'iPhone 16' } as const;

const ENV_PLACEHOLDER = /\{\{env\.([A-Za-z_][A-Za-z0-9_]*)\}\}/g;

const allSteps = (s: TestSuite): Step[] =>
  [...s.beforeAll, ...s.beforeEach, ...s.afterEach, ...s.afterAll, ...s.tests.flatMap((t) => t.steps)];

/** Every {{env.NAME}} the suites read: each needs a repo secret of the same name. */
export function collectEnvSecrets(suites: TestSuite[]): string[] {
  const names = new Set<string>();
  for (const step of suites.flatMap(allSteps)) {
    for (const value of Object.values(step.action)) {
      if (typeof value !== 'string') continue;
      for (const m of value.matchAll(ENV_PLACEHOLDER)) names.add(m[1]);
    }
  }
  return [...names].sort();
}

// Written out so TS template literals never see a `${{`
const expr = (e: string) => '${{ ' + e + ' }}';
// JSON strings are valid YAML double-quoted scalars
const q = (s: string) => JSON.stringify(s);
// Expression string literals are single-quoted; '' escapes a quote
const exprString = (s: string) => `'${s.replace(/'/g, "''")}'`;
const indent = (text: string, pad: string) => text.split('\n').map((l) => (l ? pad + l : l)).join('\n');

function header(input: CiWorkflowInput, secrets: string[], what: string[]): string {
  const lines = [
    CI_MARKER,
    '# from the Library\'s "Set up CI". suziQai overwrites this file only while the line above is first:',
    '# delete that line before hand-editing, or your edits are lost on the next "Set up CI".',
    '#',
    ...what.map((l) => `# ${l}`),
  ];
  if (secrets.length) {
    lines.push('#', '# Repo secrets to create (Settings → Secrets and variables → Actions):', ...secrets.map((s) => `#   ${s}`));
  }
  if (input.config.readOnly) {
    lines.push(
      '#',
      '# READ-ONLY: these tests run against production. The exported specs carry the read-only',
      '# network guard (non-GET requests outside the allow-list are blocked), so the command is unchanged.',
    );
  }
  return lines.join('\n');
}

function triggers(o: Required<Pick<CiWorkflowOptions, 'cron' | 'branch'>>, dispatchInputs = ''): string {
  return `on:
  push:
    branches: [${q(o.branch)}]
  pull_request:
  schedule:
    - cron: ${q(o.cron)}
  workflow_dispatch:${dispatchInputs}

# A newer push to the same ref makes the running workflow moot
concurrency:
  group: suziqai-tests-${expr('github.ref')}
  cancel-in-progress: true

permissions:
  contents: read`;
}

function envBlock(secrets: string[], prefix = ''): string {
  if (!secrets.length) return '';
  return `    env:\n${secrets.map((s) => `      ${prefix}${s}: ${expr(`secrets.${s}`)}`).join('\n')}\n`;
}

const JUNIT_SUMMARY = `const fs = require('fs');
const file = process.env.JUNIT_FILE;
const out = (s) => fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, s + '\\n');
if (!fs.existsSync(file)) { out('## suziQai tests\\n\\nNo results: the run stopped before Playwright wrote ' + file + '.'); process.exit(0); }
const xml = fs.readFileSync(file, 'utf8');
const attr = (tag, name) => Number((tag.match(new RegExp(name + '="(\\\\d+)"')) || [])[1] || 0);
const root = (xml.match(/<testsuites[^>]*>/) || [''])[0];
const total = attr(root, 'tests'), failed = attr(root, 'failures') + attr(root, 'errors'), skipped = attr(root, 'skipped');
const failing = [...xml.matchAll(/<testcase\\s+name="([^"]*)"[^>]*classname="([^"]*)"[^>]*>(?:(?!<\\/testcase>|<testcase\\b)[\\s\\S])*?<(failure|error)\\b/g)].map((m) => m[2] + ' › ' + m[1]);
out('## suziQai tests ' + (failed ? '❌' : '✅'));
out('');
out('| Passed | Failed | Skipped | Total |');
out('|---|---|---|---|');
out('| ' + (total - failed - skipped) + ' | ' + failed + ' | ' + skipped + ' | ' + total + ' |');
if (failing.length) { out(''); out('**Failing**'); failing.forEach((t) => out('- ' + t)); }
out('');
out('Full report: the \`playwright-report\` artifact on this run.');`;

function webWorkflow(input: CiWorkflowInput, secrets: string[]): string {
  const { config } = input;
  const o = input.options ?? {};
  const cron = o.cron ?? CI_DEFAULTS.cron;
  const branch = o.branch ?? CI_DEFAULTS.branch;
  const pages = o.pages ?? true;
  const wd = o.workingDirectory && o.workingDirectory !== '.' ? o.workingDirectory.replace(/\/+$/, '') : '';
  const at = (p: string) => (wd ? `${wd}/${p}` : p);
  const browser = config.browser && config.browser !== 'chromium' ? config.browser : 'chromium';
  const testDir = config.testOutputDir || 'tests';

  const what = [
    `Runs the suziQai Playwright suites in ${at(testDir)} on push to ${branch}, on pull requests,`,
    `nightly (${cron} UTC) and on demand. Reports: a pass/fail summary on each run, the Playwright`,
    'HTML report as a run artifact (14 days)' + (pages ? ', and on main/nightly runs the same report on' : '.'),
    ...(pages ? ['GitHub Pages (enable Settings → Pages → Source: GitHub Actions; the site is public unless', 'the repo is on GitHub Enterprise with private Pages).'] : []),
    // GitHub masks secrets in logs, not in artifacts: fill steps can show the typed value in the report
    ...(pages && secrets.length ? ['WARNING: the report can show values typed from secrets; turn Pages off (delete the pages job)', 'if that site is public.'] : []),
  ];

  const test = `  test:
    name: Playwright
    runs-on: ubuntu-latest
    timeout-minutes: 60
${wd ? `    defaults:\n      run:\n        working-directory: ${q(wd)}\n` : ''}${envBlock(secrets)}    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: lts/*
      - name: Install dependencies
        run: if [ -f package-lock.json ]; then npm ci; else npm install; fi
      - name: Install ${browser}
        run: npx playwright install --with-deps ${browser}
      # Failures don't stop the job here: the report and summary still need to publish
      - name: Run suites
        id: tests
        continue-on-error: true
        run: npx playwright test "$TEST_DIR" --reporter=html,github,junit
        env:
          TEST_DIR: ${q(testDir)}
          PLAYWRIGHT_HTML_OPEN: never
          PLAYWRIGHT_JUNIT_OUTPUT_NAME: results.xml
      - name: Upload HTML report
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: playwright-report
          path: ${q(at('playwright-report/'))}
          retention-days: 14
          if-no-files-found: ignore
      - name: Job summary
        if: always()
        env:
          JUNIT_FILE: results.xml
        run: |
          node - <<'EOF'
${indent(JUNIT_SUMMARY, '          ')}
          EOF
      - name: Fail if any test failed
        if: steps.tests.outcome == 'failure'
        run: exit 1`;

  // Pull requests never deploy: Pages shows the latest main/nightly run. always() so a red run's report still publishes.
  const pagesJob = `

  pages:
    name: Publish report to GitHub Pages
    needs: test
    if: always() && needs.test.result != 'cancelled' && (github.event_name == 'schedule' || github.ref == ${exprString(`refs/heads/${branch}`)})
    runs-on: ubuntu-latest
    permissions:
      pages: write
      id-token: write
    environment:
      name: github-pages
      url: ${expr('steps.deployment.outputs.page_url')}
    concurrency:
      group: suziqai-pages
      cancel-in-progress: false
    steps:
      - uses: actions/download-artifact@v4
        with:
          name: playwright-report
          path: playwright-report
      - uses: actions/upload-pages-artifact@v3
        with:
          path: playwright-report
      - id: deployment
        uses: actions/deploy-pages@v4`;

  return `${header(input, secrets, what)}
name: suziQai tests

${triggers({ cron, branch })}

jobs:
${test}${pages ? pagesJob : ''}
`;
}

const XCRESULT_SUMMARY = `const fs = require('fs');
const out = (s) => fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, s + '\\n');
let r;
try { r = JSON.parse(fs.readFileSync('summary.json', 'utf8')); } catch { out('## suziQai tests\\n\\nNo results: xcodebuild stopped before writing TestResults.xcresult.'); process.exit(0); }
const failed = r.failedTests || 0;
out('## suziQai tests ' + (failed ? '❌' : '✅'));
out('');
out('| Passed | Failed | Skipped | Total |');
out('|---|---|---|---|');
out('| ' + (r.passedTests || 0) + ' | ' + failed + ' | ' + (r.skippedTests || 0) + ' | ' + (r.totalTestCount || 0) + ' |');
const failures = r.testFailures || [];
if (failures.length) {
  out('');
  out('**Failing**');
  failures.forEach((f) => out('- ' + (f.testIdentifierString || f.testName) + ': ' + String(f.failureText || '').split('\\n')[0]));
}
out('');
out('Full results: the \`TestResults.xcresult\` artifact on this run (open in Xcode).');`;

function iosWorkflow(input: CiWorkflowInput, secrets: string[]): string {
  const o = input.options ?? {};
  const cron = o.cron ?? CI_DEFAULTS.cron;
  const branch = o.branch ?? CI_DEFAULTS.branch;
  const dir = (o.ios?.projectDir ?? '.').replace(/\/+$/, '') || '.';
  const at = (p: string) => (dir === '.' ? p : `${dir}/${p}`);
  const scheme = o.ios?.scheme ?? 'App';
  const target = o.ios?.uiTestTarget ?? `${scheme}UITests`;
  const device = o.ios?.device ?? CI_DEFAULTS.device;
  const classes = [...new Set(input.suites.map((s) => xcTestClassName(s.name)))];
  // No suites yet: run the whole UI test target rather than every test in the scheme
  const onlyTesting = (classes.length ? classes.map((c) => `${target}/${c}`) : [target])
    .map((t) => q(`-only-testing:${t}`))
    .join(' ');

  const what = [
    `Runs the suziQai XCUITest suites (${classes.join(', ') || 'none yet'}) on push to ${branch},`,
    `on pull requests, nightly (${cron} UTC) and on demand. Reports: a pass/fail summary on`,
    'each run and TestResults.xcresult as a run artifact (14 days; open it in Xcode).',
  ];
  if (secrets.length) {
    what.push(
      'Secrets reach the test process as TEST_RUNNER_<NAME> (xcodebuild strips the prefix),',
      'so XCUITests read them with ProcessInfo.processInfo.environment["<NAME>"].',
    );
  }

  const dispatch = `
    inputs:
      device:
        description: Simulator name (falls back to the first available iPhone)
        required: false
        default: ${q(device)}`;

  return `${header(input, secrets, what)}
name: suziQai tests

${triggers({ cron, branch }, dispatch)}

jobs:
  test:
    name: XCUITest
    runs-on: macos-latest
    timeout-minutes: 90
    defaults:
      run:
        working-directory: ${q(dir)}
${envBlock(secrets, 'TEST_RUNNER_')}    steps:
      - uses: actions/checkout@v4
      - name: Generate Xcode project (XcodeGen)
        run: if [ -f project.yml ]; then brew install xcodegen && xcodegen generate; fi
      # Simulator names change with each runner image; take the first iPhone if ours is missing
      - name: Pick simulator
        env:
          WANTED: ${expr(`inputs.device || ${exprString(device)}`)}
        run: |
          if xcrun simctl list devices available | grep -q "    $WANTED ("; then
            DEVICE="$WANTED"
          else
            DEVICE=$(xcrun simctl list devices available | grep -m1 -oE 'iPhone[^(]*' | sed 's/ *$//')
            echo "::warning::Simulator '$WANTED' isn't on this runner; using '$DEVICE'"
          fi
          echo "DEVICE=$DEVICE" >> "$GITHUB_ENV"
      # Failures don't stop the job here: the result bundle and summary still need to publish
      - name: Run suites
        id: tests
        continue-on-error: true
        run: |
          xcodebuild test \\
            -scheme ${q(scheme)} \\
            -destination "platform=iOS Simulator,name=$DEVICE" \\
            -resultBundlePath TestResults.xcresult \\
            ${onlyTesting}
      - name: Upload result bundle
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: TestResults.xcresult
          path: ${q(at('TestResults.xcresult'))}
          retention-days: 14
          if-no-files-found: ignore
      - name: Job summary
        if: always()
        run: |
          xcrun xcresulttool get test-results summary --path TestResults.xcresult > summary.json 2>/dev/null || true
          node - <<'EOF'
${indent(XCRESULT_SUMMARY, '          ')}
          EOF
      - name: Fail if any test failed
        if: steps.tests.outcome == 'failure'
        run: exit 1
`;
}

/** GitHub Actions workflow that runs a project's exported suites and publishes GitHub-native reports. */
export function generateCiWorkflow(input: CiWorkflowInput): string {
  const secrets = collectEnvSecrets(input.suites);
  return input.config.platform === 'ios' ? iosWorkflow(input, secrets) : webWorkflow(input, secrets);
}

/** True for a file suziQai generated (and may therefore overwrite). */
export function isSuziqaiWorkflow(content: string): boolean {
  return content.split('\n', 1)[0].startsWith(CI_MARKER);
}
