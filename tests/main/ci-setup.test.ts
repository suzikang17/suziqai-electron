// @vitest-environment node
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { execFileSync } from 'child_process';
import { mkdtemp, rm, readFile, writeFile, mkdir, realpath } from 'fs/promises';
import path from 'path';
import os from 'os';
import { detectIosProject, setUpCi, writeWorkflowFile } from '../../src/main/ci-setup';
import { CI_MARKER, CI_WORKFLOW_PATH } from '../../src/shared/utils/generateCiWorkflow';
import type { ProjectConfig, TestSuite } from '../../src/shared/types';

const webConfig: ProjectConfig = {
  platform: 'web', baseUrl: 'http://localhost:3000', browser: 'chromium', testOutputDir: 'tests', locatorStrategy: 'recommended',
};
const suite: TestSuite = {
  id: 's', name: 'Login', fileName: 'login', beforeAll: [], beforeEach: [], afterEach: [], afterAll: [], devices: [],
  tests: [{ id: 'b', name: 'ok', steps: [{ id: '1', label: 'fill', status: 'passed', action: { type: 'fill', selector: 'x', value: '{{env.PW}}' } }] }],
};

describe('ci-setup', () => {
  let dir: string;
  beforeEach(async () => { dir = await realpath(await mkdtemp(path.join(os.tmpdir(), 'ci-setup-'))); });
  afterEach(async () => { await rm(dir, { recursive: true, force: true }); });

  describe('writeWorkflowFile', () => {
    const file = () => path.join(dir, CI_WORKFLOW_PATH);

    it('creates .github/workflows and writes the file', async () => {
      expect(await writeWorkflowFile(dir, `${CI_MARKER}\nname: a\n`)).toBe(file());
      expect(await readFile(file(), 'utf-8')).toBe(`${CI_MARKER}\nname: a\n`);
    });

    it('overwrites a file suziQai generated', async () => {
      await writeWorkflowFile(dir, `${CI_MARKER}\nname: a\n`);
      await writeWorkflowFile(dir, `${CI_MARKER}\nname: b\n`);
      expect(await readFile(file(), 'utf-8')).toContain('name: b');
    });

    it('refuses to overwrite a file without the marker on its first line', async () => {
      await mkdir(path.dirname(file()), { recursive: true });
      await writeFile(file(), `name: hand-made\n${CI_MARKER}\n`);
      await expect(writeWorkflowFile(dir, `${CI_MARKER}\nname: b\n`)).rejects.toThrow(/wasn't generated by suziQai/);
      expect(await readFile(file(), 'utf-8')).toBe(`name: hand-made\n${CI_MARKER}\n`);
    });
  });

  describe('setUpCi', () => {
    it('errors clearly outside a git repository', async () => {
      await expect(setUpCi(dir, webConfig, [suite])).rejects.toThrow(/isn't in a git repository/);
    });

    it('writes at the repo root, runs from the project subdirectory, and returns the secrets', async () => {
      execFileSync('git', ['init', '-q'], { cwd: dir });
      const project = path.join(dir, 'apps', 'web');
      await mkdir(project, { recursive: true });
      const result = await setUpCi(project, webConfig, [suite]);
      expect(result).toEqual({ path: path.join(dir, CI_WORKFLOW_PATH), secrets: ['PW'] });
      const yaml = await readFile(result.path, 'utf-8');
      expect(yaml).toContain('working-directory: "apps/web"');
      expect(yaml).toContain('PW: ${{ secrets.PW }}');
    });
  });

  describe('detectIosProject', () => {
    it('finds an XcodeGen project in ios/ and takes the scheme from its name', async () => {
      await mkdir(path.join(dir, 'ios'));
      await writeFile(path.join(dir, 'ios', 'project.yml'), '# comment\nname: PetHomepage\noptions:\n  bundleIdPrefix: x\n');
      expect(await detectIosProject(dir, dir)).toEqual({ projectDir: 'ios', scheme: 'PetHomepage' });
    });

    it('falls back to the .xcodeproj name in the project dir itself', async () => {
      await mkdir(path.join(dir, 'App.xcodeproj'));
      expect(await detectIosProject(dir, dir)).toEqual({ projectDir: '.', scheme: 'App' });
    });
  });
});
